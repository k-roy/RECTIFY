def _iter_n_ops(
    read: pysam.AlignedSegment,
) -> Iterator[Tuple[int, int, int, int]]:
    """Yield (cigar_idx, ref_start, ref_end, q_split) for each N-op.

    q_split = number of query-consuming bases consumed before this N-op,
    counting only bases from aligned (reference-consuming) regions and their
    adjacent soft-clips.  Leading H/S ops are excluded; trailing S at the 5'
    RNA end (right side for is_reverse reads) are included after the last
    ref-consuming op.

    H ops never appear in query_sequence and are always skipped.
    S ops at the start of the CIGAR (before any reference-consuming op) are
    leading soft-clips and do NOT count toward q_split.
    S ops after at least one ref-consuming op (trailing in genomic terms) DO
    count toward q_split.

    The genomic cursor advances on ``_REF_CONSUMING_POS`` (M/D/=/X **and N**):
    an intron consumes reference, so a walker that skipped it reported every
    N-op after the first short by the summed length of the preceding introns
    (ISSUE-004).
    """
    q_pos = 0
    r_pos = read.reference_start
    seen_ref_op = False   # True once at least one ref-consuming op has been processed

    for i, (op, length) in enumerate(read.cigartuples):
        if op == _H:
            continue  # H never in query_sequence; skip entirely
        if op == _N:
            yield i, r_pos, r_pos + length, q_pos
        if op in _REF_CONSUMING_POS:
            r_pos += length
        if op in _REF_CONSUMING:
            # q_split semantics unchanged: a leading soft-clip is one that
            # precedes the first ALIGNED op, so N does not open the alignment.
            seen_ref_op = True
        if op in _QUERY_CONSUMING and op != _S:
            q_pos += length
        elif op == _S:
            # Count soft-clip only if we have already seen a reference-consuming op
            # (i.e., this is NOT a leading soft-clip)
            if seen_ref_op:
                q_pos += length


def _dn_run_extent(
    cigartuples: List[Tuple[int, int]],
    cigar_idx: int,
    ns: int,
    ne: int,
) -> Tuple[int, int]:
    """Reference extent of the D/N run containing the N-op at *cigar_idx*.

    ``junction_scoring._merge_del_into_intron`` collapses any run of adjacent
    D/N ops containing an N into a single N — RECTIFY's stated convention that
    ``1D 112N`` and ``113N`` are the same intron, since D and N both consume
    reference and no query.  The junction POOL is built through that
    normalization, but ``_iter_n_ops`` reports the RAW N-op, so for a read with
    ``111N 3D`` the pool holds a junction 3 bp longer than the one the read is
    scored at.

    That twin is not an alternative placement: the read's bases sit in exactly
    the same reference positions either way.  Returning its extent lets the
    refiner recognise and skip it (see ``refine_read_junctions``).
    """
    start, end = ns, ne
    k = cigar_idx - 1
    while k >= 0 and cigartuples[k][0] in (_D, _N):
        start -= cigartuples[k][1]
        k -= 1
    k = cigar_idx + 1
    while k < len(cigartuples) and cigartuples[k][0] in (_D, _N):
        end += cigartuples[k][1]
        k += 1
    return start, end


def _has_boundary_error(
    cigartuples: List[Tuple[int, int]],
    intron_start: int,
    intron_end: int,
    ref_start: int,
    window: int,
) -> bool:
    """Return True if there is an X (mismatch) or I/D (indel) op within
    *window* reference bases of either the intron_start or intron_end boundary.

    This is used as a pre-filter for junction refinement: only reads with
    alignment evidence of a boundary problem (noisy bases near the splice site)
    benefit from re-scoring; clean M-op alignments indicate the aligner was
    already confident.

    Args:
        cigartuples:  Read CIGAR tuples.
        intron_start: Left boundary of the N-op (0-based).
        intron_end:   Right boundary of the N-op (0-based, exclusive).
        ref_start:    Read reference_start.
        window:       Reference distance from either boundary to search.

    Returns:
        True if any X, I, or D op falls within *window* bp of intron_start or
        intron_end; False otherwise.
    """
    if not cigartuples:
        return False

    # Ops of interest: X (mismatch), I (insertion), D (deletion)
    _error_ops = frozenset([_D, _I, _X])
    _ref_ops   = frozenset([_M, _D, _EQ, _X])  # ops that advance ref pos

    ref_pos = ref_start
    for op, length in cigartuples:
        if op == _H:
            continue
        if op == _N:
            ref_pos += length
            continue
        if op in _error_ops:
            # The reference span of this op is [ref_pos, ref_pos + ref_len)
            ref_len = length if op in _ref_ops else 0
            op_end  = ref_pos + ref_len  # exclusive

            # Check proximity to intron_start
            if ref_pos <= intron_start + window and op_end >= intron_start - window:
                return True
            # Check proximity to intron_end
            if ref_pos <= intron_end + window and op_end >= intron_end - window:
                return True
        if op in _ref_ops:
            ref_pos += length
        # S/I: don't advance ref

    return False


# Only the four real DNA bases can constitute a homopolymer run or a microhomology
# match; a shared ambiguity code (N) or non-ACGT symbol must NOT (audit A5).
_ACGT = frozenset("ACGT")


def _hp_run_across(seq: str, pos: int, min_run: int) -> int:
    """If a junction boundary at *pos* (between ``seq[pos-1]`` and ``seq[pos]``) sits
    INSIDE a reference homopolymer run — same base on both sides — return that run's
    length; otherwise 0.

    This is the HP-drift-guard detector.  Ubiquitous ONT homopolymer undercalls let
    an evidence-only re-placer slide a junction boundary *within* a run (re-parti-
    tioning identical bases between intron and exon) — fabricating a false
    non-canonical junction.  A move that lands a boundary inside a run (this returns
    >0) is required to clear a stronger evidence margin; a move to a genuine sequence
    TRANSITION (``seq[pos-1] != seq[pos]`` → 0 here), e.g. a real non-canonical
    acceptor, is untouched.  So motif-blind discovery is preserved everywhere except
    the one spot ubiquitous undercalls make the evidence untrustworthy."""
    n = len(seq)
    if pos <= 0 or pos >= n:
        return 0
    b = seq[pos]
    if b not in _ACGT:
        return 0                    # ambiguity/non-ACGT (N) run is NOT a homopolymer
    if b != seq[pos - 1]:
        return 0                    # boundary is a sequence transition, not in a run
    i = pos - 1
    while i > 0 and seq[i - 1] == b:
        i -= 1
    j = pos
    while j < n - 1 and seq[j + 1] == b:
        j += 1
    run = j - i + 1
    return run if run >= min_run else 0


def _frac_match(a: str, b: str) -> float:
    """Fraction of positions where equal-length strings *a* and *b* agree (0.0 if
    empty or mismatched length).

    Only ACGT bases can MATCH: a shared ambiguity code (N==N, or lowercase/non-ACGT)
    is NOT counted as agreement.  Genome ambiguity runs (N…N, gaps) would otherwise
    score frac 1.0 → a phantom microhomology that falsely vetoes a genuine move
    (audit A5).  x==y with x in _ACGT ⇒ both are the same real base."""
    if not a or len(a) != len(b):
        return 0.0
    return sum(1 for x, y in zip(a, b) if x == y and x in _ACGT) / len(a)


def _move_microhomology(seq: str, ns: int, ne: int, js: int, je: int) -> float:
    """Microhomology-drift-guard detector (the general, non-homopolymer analog of
    ``_hp_run_across``).

    For a candidate junction move ``(ns, ne) -> (js, je)`` that shifts the donor
    and/or acceptor by ``k`` bp, return the FRACTION of the shifted ``k``-mer that
    REPEATS at the drift distance — i.e. how much local microhomology (a near-tandem
    direct repeat) makes the ``k``-bp boundary drift near-tied by evidence.

    Mechanism (spike-in-confirmed): a canonical junction fabricates a false
    NON-canonical junction only when the ``k`` bases that flip between exon and intron
    near-match the ``k`` bases at the drift distance (so ONT error tips the near-tie).
    A homopolymer is the MAXIMAL case (frac -> 1.0); this catches the PARTIAL-repeat
    non-HP drift the HP-guard misses.  A move to a genuine sequence transition (a real
    non-canonical splice site) has LOW microhomology (~0.25 random) and is untouched,
    preserving motif-blind discovery.

    Combination rule = MIN over the boundaries that ACTUALLY MOVED (audit A8): a move is
    drift-suspect only if EVERY shifted boundary sits in microhomology.  A genuine
    sequence TRANSITION on any moved boundary (low frac) SPARES the whole move — an
    unrelated tandem repeat on the OTHER boundary must not mask it (max() did, vetoing
    e.g. a both-boundary move whose donor abuts a (CAG)n microsatellite but whose
    acceptor is a real non-canonical transition).  A boundary that moved but runs off
    the genome edge (unassessable) contributes 0.0 → does not flag (favours discovery).
    Single-boundary moves are unchanged (min == that boundary's frac)."""
    n = len(seq)
    fracs: List[float] = []
    # Acceptor shift (intron|exon2): a k-bp slide between the two candidate acceptors is
    # enabled by a DOWNSTREAM tandem repeat seq[lo:hi] ~ seq[hi:hi+k] (the read's exon2
    # start k-mer repeats at the drift distance).  Direction-independent in lo/hi.
    if je != ne:
        lo, hi = (ne, je) if ne < je else (je, ne)
        k = hi - lo
        fracs.append(_frac_match(seq[lo:hi], seq[hi:hi + k]) if hi + k <= n else 0.0)
    # Donor shift (exon1|intron): enabled by an UPSTREAM tandem repeat
    # seq[lo-k:lo] ~ seq[lo:hi] (the read's exon1 end k-mer repeats upstream).
    if js != ns:
        lo, hi = (ns, js) if ns < js else (js, ns)
        k = hi - lo
        fracs.append(_frac_match(seq[lo - k:lo], seq[lo:hi]) if lo - k >= 0 else 0.0)
    return min(fracs) if fracs else 0.0


def _effective_veto_margin(hold_margin: float, eff_margin: float,
                           drift_near_tie_cap: float) -> float:
    """Effective move-veto margin after the read-evidence near-tie cap.

    ``eff_margin`` = ``hold_margin`` + drift-flagged additions (hp_drift + microhom_drift).
    The drift additions are decided from GENOMIC context ONLY (``_move_microhomology`` /
    ``_hp_run_across`` are read-blind), so on their own they can veto a move the READ
    strongly supports (a real cryptic the read distinguishes, delta_improve > 0).  When
    ``drift_near_tie_cap`` > 0, cap the DRIFT portion so the veto fires only within a
    near-tie band, while NEVER capping ``hold_margin`` (the read-agnostic blunt prior):

        veto_margin = max(hold_margin, min(eff_margin, drift_near_tie_cap))

    Consequence: a move with ``delta_improve >= drift_near_tie_cap`` is never drift-vetoed,
    bounding the read-blind discovery-loss.  HONEST SCOPE (see MICROHOM_AUDIT_SYNTHESIS.md):
    delta_improve, eff_margin and the cap share the SAME score axis, so the cap BOUNDS —
    it does not add a discriminating signal inside the ``(0, cap)`` near-tie band, where
    real cryptics and fabricated drift still overlap.  Cap disabled (<= 0.0) OR no drift
    margin added (eff_margin == hold_margin) → returns ``eff_margin`` unchanged
    (byte-identical to the pre-cap veto).
    """
    if drift_near_tie_cap > 0.0 and eff_margin > hold_margin:
        return max(hold_margin, min(eff_margin, drift_near_tie_cap))
    return eff_margin


def _semiglobal_ed(query: str, ref: str) -> int:
    """Edit distance aligning ALL of ``query`` to a PREFIX of ``ref`` (free ref suffix, HARD-
    anchored at ``ref[0]`` — no free query/ref prefix).  Indel-tolerant; lower = query matches
    ref better.  O(len(query)·len(ref)); only called on the rare would-be-veto path."""
    m, n = len(query), len(ref)
    if m == 0:
        return 0
    if n == 0:
        return m
    prev = list(range(n + 1))
    for i in range(1, m + 1):
        cur = [i] + [0] * n
        qi = query[i - 1]
        for j in range(1, n + 1):
            cost = 0 if qi == ref[j - 1] else 1
            cur[j] = min(prev[j - 1] + cost, prev[j] + 1, cur[j - 1] + 1)
        prev = cur
    return min(prev)


def _positional_signal(genome_seq: str, q: str, q_split: int, ne: int, new_je: int,
                       W: int = 28) -> Optional[int]:
    """Indel-robust positional-distinctiveness signal for an ACCEPTOR move ``ne -> new_je``.

    ``ed(rescue, incumbent exon2) - ed(rescue, moved exon2)`` where ``rescue = q[q_split:]`` is the
    read's exon2 bases.  ``> 0`` ⇒ the read's exon2 matches the MOVED acceptor better, i.e. genuine
    read evidence for the move — the discriminating bases the scorer's free-``k`` soft-clip escape
    HIDES from ``delta_improve``.  Hard-anchored (no free-prefix split) is exactly what removes that
    escape (panel: cap+ed(>0) → ~0.3% discovery loss at ~cap-alone fabrication; 98–99% balanced
    separation of real cryptics vs error-driven drift in the delta overlap band).

    ACCEPTOR-ONLY by design.  ``_score_junction`` is acceptor-centric (``intron_start`` is unused →
    the donor does not affect a candidate's score), so the refiner never discovers a donor-only move
    (both candidates tie → is_alt keeps the incumbent) — there is no donor-side discovery-loss to
    close.  For a both-boundary candidate the read's exon1 matches the aligner-placed (incumbent)
    donor, so a donor edit-distance term would go NEGATIVE and could drag a genuine acceptor cryptic's
    positive signal down, wrongly vetoing a real discovery.  So the discrimination lives entirely on
    the acceptor/exon2 side that actually drives placement.  (See DISCOVERY_LOSS_PANEL_RESULT.md.)

    Returns ``None`` when the acceptor did not move (exon2 discrimination undefined) or the rescue is
    empty — callers then leave the veto to the margin/cap alone (conservative)."""
    if new_je == ne:
        return None
    rescue = q[q_split:q_split + W]
    if not rescue:
        return None
    n = len(genome_seq)
    ref_inc = genome_seq[ne:min(n, ne + W + 6)]
    ref_mov = genome_seq[new_je:min(n, new_je + W + 6)]
    return _semiglobal_ed(rescue, ref_inc) - _semiglobal_ed(rescue, ref_mov)


def _n_op_index_at(
    cigartuples: List[Tuple[int, int]], ref_start: int, ns: int, ne: int,
) -> int:
    """Index of the N op spanning exactly ``[ns, ne)``, or -1."""
    pos = ref_start
    for i, (op, length) in enumerate(cigartuples):
        if op == _N and pos == ns and pos + length == ne:
            return i
        if op in _REF_CONSUMING_POS:
            pos += length
    return -1


def _anchor_run(
    cigartuples: List[Tuple[int, int]], k: int, step: int,
) -> Tuple[Optional[int], int]:
    """``(abutting_op, aligned_run)`` walking from op *k* in direction *step*.

    ``abutting_op`` is the op that touches the N on that side (None past the
    CIGAR end); ``aligned_run`` is the length of the contiguous M/=/X run there
    (0 when the abutting op is not an aligned-match op)."""
    j = k + step
    if not (0 <= j < len(cigartuples)):
        return None, 0
    abutting = cigartuples[j][0]
    run = 0
    while 0 <= j < len(cigartuples) and cigartuples[j][0] in (_M, _EQ, _X):
        run += cigartuples[j][1]
        j += step
    return abutting, run


def _alternative_within_delta(
    chrom: str, js: int, je: int, genome_seq: str, strand: str,
    annotated_set: Set[Junction],
) -> bool:
    """True when an annotated or canonical-class junction other than ``(js, je)``
    lies in the delta box around it.  The per-boundary delta widens from
    ``_NONCANON_DELTA`` to ``_NONCANON_DELTA_HP`` when that boundary sits inside a
    homopolymer run of >= ``_NONCANON_HP_RUN`` (ONT undercalls make a slide within
    a run indistinguishable)."""
    ds = (_NONCANON_DELTA_HP if _hp_run_across(genome_seq, js, _NONCANON_HP_RUN)
          else _NONCANON_DELTA)
    de = (_NONCANON_DELTA_HP if _hp_run_across(genome_seq, je, _NONCANON_HP_RUN)
          else _NONCANON_DELTA)
    for a in range(-ds, ds + 1):
        for b in range(-de, de + 1):
            if a == 0 and b == 0:
                continue
            s, e = js + a, je + b
            if e <= s:
                continue
            if (chrom, s, e) in annotated_set:
                return True
            if _canonical_tier(s, e, genome_seq, strand) <= _CANONICAL_TIER_MAX:
                return True
    return False


def _realizable(
    read: pysam.AlignedSegment,
    cigar_idx: int,
    ns: int,
    ne: int,
    new_js: int,
    new_je: int,
    genome_seq: str,
    strand: str,
    hp_pen: float,
    W: int,
) -> bool:
    """True when ``_apply_junction_replacement`` would WRITE the move
    ``(ns, ne) -> (new_js, new_je)`` for *read* — a dry run on a copy.

    The surgery refuses a move for structural reasons the scorer never sees
    (boundary shift beyond the guard, reference/query span mismatch, a
    both-boundary move that raises the read's indel burden).  A candidate it
    refuses is not a placement this read can carry, so ``refine_read_junctions``
    ranks only candidates that pass here.  Any exception counts as a refusal."""
    try:
        trial = read.__copy__()
        return bool(_apply_junction_replacement(
            trial, cigar_idx, ns, ne, new_js, new_je, genome_seq, strand, hp_pen, W,
        ))
    except Exception:
        return False


def _annotated_alternative(
    ranked: List[tuple],
    chrom: str,
    js: int,
    je: int,
    genome_seq: str,
    strand: str,
    annotated_set: Set[Junction],
    delta: int = _ANNOT_ALT_DELTA,
) -> Optional[tuple]:
    """The best-ranked SCORED candidate that is annotated, canonical-class,
    shares one boundary exactly with ``(js, je)`` and lies within *delta* of it
    on the other; None when there is none.  *ranked* is the sorted list of
    ``refine_read_junctions``' candidate tuples (``js``/``je`` at [5]/[6])."""
    for tup in ranked:
        s, e = tup[5], tup[6]
        if (s, e) == (js, je):
            continue
        same_donor = (s == js and 0 < abs(e - je) <= delta)
        same_acceptor = (e == je and 0 < abs(s - js) <= delta)
        if not (same_donor or same_acceptor):
            continue
        if (chrom, s, e) not in annotated_set:
            continue
        if _canonical_tier(s, e, genome_seq, strand) > _CANONICAL_TIER_MAX:
            continue
        return tup
    return None


def _noncanon_destination_refusal(
    read: pysam.AlignedSegment,
    cigar_idx: int,
    ns: int,
    ne: int,
    new_js: int,
    new_je: int,
    genome_seq: str,
    strand: str,
    chrom: str,
    annotated_set: Set[Junction],
    hp_pen: float,
    W: int,
) -> str:
    """'' when a canonical-class -> unannotated non-canonical move carries a
    preponderance of evidence, else the refusal token (see NONCANON_REFUSALS and
    the module comment above _NONCANON_PREPONDERANCE).

    The post-move anchors are read from a DRY RUN of the real surgery on a copy of
    the read, so the test sees exactly the CIGAR that would be written.  A move the
    surgery itself refuses (span mismatch, shift guard, both-boundary invariant)
    returns '' — that refusal is not this gate's to count."""
    if _alternative_within_delta(chrom, new_js, new_je, genome_seq, strand, annotated_set):
        return 'alternative_within_delta'
    try:
        trial = read.__copy__()
        applied = _apply_junction_replacement(
            trial, cigar_idx, ns, ne, new_js, new_je, genome_seq, strand, hp_pen, W,
        )
    except Exception:
        applied = False
    if not applied:
        return ''
    new_cigar = list(trial.cigartuples)
    k = _n_op_index_at(new_cigar, trial.reference_start, new_js, new_je)
    if k < 0:
        return 'anchor_below_floor'          # no locatable N: no anchor to speak of
    left_op, left_run = _anchor_run(new_cigar, k, -1)
    right_op, right_run = _anchor_run(new_cigar, k, +1)
    if left_op in (_I, _D) or right_op in (_I, _D):
        return 'adjacent_indel'
    old_indel = sum(l for op, l in read.cigartuples if op in (_I, _D))
    new_indel = sum(l for op, l in new_cigar if op in (_I, _D))
    if new_indel > old_indel:
        return 'indel_burden'
    # Lazy: splice_aware_5prime imports this module.
    from .splice_aware_5prime import min_informative_clip_bp
    floor = min_informative_clip_bp()
    if left_run < floor or right_run < floor:
        return 'anchor_below_floor'
    gs = len(genome_seq)
    left_len = min(left_run, _NONCANON_ANCHOR_ASSESS_BP)
    right_len = min(right_run, _NONCANON_ANCHOR_ASSESS_BP)
    left_seq = genome_seq[max(0, new_js - left_len):new_js]
    right_seq = genome_seq[new_je:min(gs, new_je + right_len)]
    need_left = max(1, abs(new_js - ns))
    need_right = max(1, abs(new_je - ne))
    if (max_search_window_bp(left_seq, max_window=_NONCANON_ANCHOR_ASSESS_BP) < need_left
            or max_search_window_bp(right_seq, max_window=_NONCANON_ANCHOR_ASSESS_BP) < need_right):
        return 'anchor_uninformative'
    return ''


def refine_read_junctions(
    read: pysam.AlignedSegment,
    all_junctions_idx: Dict[str, List[Tuple[int, int]]],
    annotated_set: Set[Junction],
    genome_seq: str,
    strand: str,
    hp_pen: float = 0.25,
    W: int = 15,
    max_slide: int = 10,
    search_radius: int = 5000,
    max_boundary_shift: int = 50,
    boundary_error_window: int = 10,
    max_junction_size: Optional[int] = None,
    max_candidates_per_nop: Optional[int] = None,
    profile: Optional[JunctionRefineProfile] = None,
    penalty_table: Optional[HpPenaltyTable] = None,
    motif_blind: bool = False,
    hold_margin: float = 0.0,
    hp_drift_margin: float = 0.0,
    hp_drift_min_run: int = 4,
    microhom_drift_margin: float = 0.0,
    microhom_threshold: float = 0.5,
    drift_near_tie_cap: float = 0.0,
    drift_positional_gate: float = 0.0,
    counters: Optional[Counter] = None,
) -> List[Tuple[int, int, int, int, int]]:
    """Find improved junctions for all N-ops in a read.

    Args:
        read:                 pysam AlignedSegment (not modified).
        counters:             Optional ``collections.Counter`` the driver owns;
                              refusal tokens that must reach the run's stats
                              line (``noncanon_destination_refused``) are
                              counted here whether or not a profile is on.
        all_junctions_idx:    Output of _build_junction_index.
        annotated_set:        Set of (chrom, js, je) for annotated junctions.
        genome_seq:           Full chromosome sequence.
        strand:               '+' or '-'.
        hp_pen:               Homopolymer indel penalty.
        W:                    Retained for API compatibility; unused by the
                              current HP-anchored semi-global implementation.
        max_slide:            Retained for API compatibility; unused by the
                              current HP-anchored semi-global implementation.
        search_radius:        Discovery radius for finding candidate junctions
                              (bp).  Large values ensure annotated junctions from
                              adjacent isoforms are included.
        max_boundary_shift:   Maximum allowed shift of either intron boundary
                              (bp).  Candidates where |new_ns - old_ns| or
                              |new_ne - old_ne| exceeds this threshold are
                              excluded.  Prevents pairing with junctions from
                              neighbouring genes that happen to score well due to
                              sequence coincidence in noisy Nanopore reads.
        boundary_error_window: Only refine N-ops that have at least one
                              mismatch (X) or indel (I/D) op within this many
                              reference bases of either junction boundary.
                              Reads with clean M-op alignments at the boundary
                              are already correctly placed and don't need
                              refinement.  Set to 0 to disable this filter and
                              score every N-op.
        max_junction_size:    Optional maximum candidate intron/junction length.
                              For yeast, 10000 keeps organism-plausible
                              junctions while removing long noisy N-op calls.
        max_candidates_per_nop:
                              Optional deterministic cap on candidates scored
                              per N-op after ranking current/annotated/nearby
                              candidates first.
        profile:              Optional aggregate profiler.

    Returns:
        List of (cigar_idx, old_start, old_end, new_start, new_end) for each
        N-op that should be updated.  Empty if no changes needed.
    """
    if not read.cigartuples or read.is_unmapped:
        return []

    chrom = standardize_chrom_name(read.reference_name)
    q = read.query_sequence
    if not q:
        return []
    # ISSUE-021: ``_iter_n_ops`` counts ``q_split`` from the first ALIGNED query
    # base — a LEADING soft clip is excluded by design — but ``q`` is pysam's
    # ``query_sequence``, which INCLUDES the soft-clipped bases.  Indexing ``q``
    # with the raw ``q_split`` started every rescue window ``len(clip)`` bases
    # too early, inside exon 1 (a 71-nt clip put the whole 30-nt window in
    # exon 1), so every N-op of a soft-clipped read was scored on the wrong
    # bases.  Add the clip length ONCE here so that every consumer below
    # (``_score_junction``, ``_positional_signal``) indexes ``query_sequence``
    # in one coordinate system.  ``query_alignment_start`` is exactly the
    # leading-S length (H is not in ``query_sequence``; a leading I is not a
    # clip and is already counted by ``_iter_n_ops``).  Chosen over switching
    # ``q`` to ``query_alignment_sequence`` because that would also drop a
    # TRAILING clip, changing the window after a short last exon for every
    # trailing-clipped read — a different behavior from the one this fixes.
    # The surgery (``_apply_junction_replacement``) walks the CIGAR and never
    # indexes ``q``, so the preponderance gate's dry run needs no change.
    q_clip = read.query_alignment_start

    replacements = []

    for cigar_idx, ns, ne, q_split in _iter_n_ops(read):
        q_split += q_clip   # index into query_sequence (see ISSUE-021 above)
        if profile is not None:
            profile.inc('n_ops_examined')
        # Filter: only score junctions where there is alignment evidence of a
        # boundary problem — an X (mismatch) or I/D (indel) op within
        # boundary_error_window reference bases of either junction endpoint.
        # Clean M-op alignments at the boundary indicate the aligner was
        # confident; noisy boundaries are the cases that benefit from refinement.
        # Exception: junctions that are not a proper GT/GC..AG (tier >
        # _CANONICAL_TIER_MAX, e.g. a GG/AT donor OR a non-AG acceptor) are
        # ALWAYS scored regardless of boundary cleanliness — the aligner can
        # produce a locally-optimal but canonically-wrong split with no nearby
        # errors (e.g. 54= leading into a GG donor), and these are exactly the
        # cases that need correction.  This bypass used to require tier >= 4,
        # i.e. a broken DONOR, so a cleanly-aligned GT-AT (tier 3) or GT-GG
        # (tier 2) N-op was never even scored: panel reads bc1283c7 and
        # 12b2bc34 sat 6-7 nt from an annotated GT-AG with no indel within the
        # boundary window, and 2H never looked at them.
        if boundary_error_window > 0:
            _t_boundary = time.perf_counter() if profile is not None else 0.0
            has_boundary_error = _has_boundary_error(
                read.cigartuples, ns, ne,
                read.reference_start, boundary_error_window,
            )
            _profile_time(profile, 'boundary_error_filter', _t_boundary)
            if not has_boundary_error:
                _t_tier = time.perf_counter() if profile is not None else 0.0
                current_filter_tier = _canonical_tier(ns, ne, genome_seq, strand)
                _profile_time(profile, 'canonical_tier_current_filter', _t_tier)
                if current_filter_tier <= _CANONICAL_TIER_MAX:
                    if profile is not None:
                        profile.inc('n_ops_skipped_boundary_clean')
                    continue
                if profile is not None:
                    profile.inc('n_ops_noncanonical_bypass_boundary_filter')
        # Use search_radius to discover candidates (finds annotated junctions from
        # adjacent isoforms), but constrain each endpoint to max_boundary_shift to
        # avoid pairing with junctions from entirely different genes.
        _t_candidates = time.perf_counter() if profile is not None else 0.0
        candidates = _candidates_near(
            all_junctions_idx, chrom, ns, ne,
            radius=search_radius,
            start_radius=max_boundary_shift,
            end_radius=max_boundary_shift,
            max_junction_size=max_junction_size,
        )
        _profile_time(profile, 'candidate_lookup', _t_candidates)
        if profile is not None:
            profile.observe_candidates(len(candidates))
        if not candidates:
            if profile is not None:
                profile.inc('n_ops_no_candidates')
            continue

        if max_candidates_per_nop and max_candidates_per_nop > 0:
            _t_cap = time.perf_counter() if profile is not None else 0.0
            capped_candidates = _rank_and_cap_candidates(
                candidates, chrom, ns, ne, annotated_set, max_candidates_per_nop
            )
            _profile_time(profile, 'candidate_rank_and_cap', _t_cap)
            if profile is not None:
                profile.observe_candidates(len(capped_candidates), after_cap=True)
                if len(capped_candidates) < len(candidates):
                    profile.inc('n_ops_candidate_capped')
                    profile.inc('candidates_dropped_by_cap', len(candidates) - len(capped_candidates))
            candidates = capped_candidates
        elif profile is not None:
            profile.observe_candidates(len(candidates), after_cap=True)

        if profile is not None:
            profile.inc('n_ops_scored')
            profile.inc('candidates_scored', len(candidates))

        # All candidates are scored; canonical/annotated status is used ONLY as
        # a tie-breaker for equal or near-equal sequence scores.
        # Policy: a non-canonical junction with ed=0 always beats canonical with
        # ed≥1.0; within the sub-integer HP noise floor (|ed_A - ed_B| < 1.0)
        # canonical annotated junctions are preferred.

        ranked: List[tuple] = []   # every candidate's (score_cmp, pri2, pri3, is_novel, move_dist, js, je, delta)
        incumbent_score = None   # score_cmp of the current placement (for hold_margin)
        incumbent_tuple = None   # the incumbent's own ranking tuple (None when it is not a candidate)

        def _bump(key: str) -> None:
            """Count a decision-level event on the profile and the driver's counters."""
            if profile is not None:
                profile.inc(key)
            if counters is not None:
                counters[key] += 1

        # Canonical tier of the current N-op determines tie-break priority ordering.
        # When the current junction is NOT a proper GT/GC..AG junction
        # (tier > _CANONICAL_TIER_MAX), a canonical alternative should be preferred
        # at equal edit-distance score (i.e., tier comparison wins over is_alt).
        # When it IS one (tier <= _CANONICAL_TIER_MAX), the read was placed there
        # for good reason and the current junction is preferred at equal score
        # (is_alt wins over tier).
        _t_tier = time.perf_counter() if profile is not None else 0.0
        current_tier = _canonical_tier(ns, ne, genome_seq, strand)
        _profile_time(profile, 'canonical_tier_current_scoring', _t_tier)
        # Motif-blind (arm-B): decide placement on read evidence alone.  The current
        # junction's canonicity never triggers a canonical preference (so the
        # _CANONICAL_HP_PRIOR discount below is also disabled), and tier / is_novel
        # are dropped from the tie-break sort (below).  motif_blind=False is
        # byte-identical to the incumbent (arm-A).
        tier_beats_alt = (current_tier > _CANONICAL_TIER_MAX) and not motif_blind

        # The read's own junction as the POOL spells it: `_merge_del_into_intron`
        # folds a D abutting an N into the intron, so a read with `111N 3D`
        # contributes a junction 3 bp longer than the N-op it is scored at. The
        # twin is the SAME alignment — identical reference span, identical query
        # bases, only the op labels differ — so choosing between the two is a
        # REPRESENTATION question, and the scorer is the wrong instrument for it
        # (see the candidate loop).
        _dn_twin = _dn_run_extent(read.cigartuples, cigar_idx, ns, ne)

        for js, je in candidates:
            if je <= js:
                if profile is not None:
                    profile.inc('candidates_invalid')
                continue
            if (js, je) == _dn_twin and (js, je) != (ns, ne):
                # Neither representation is universally right — the ANNOTATION is
                # what decides which one this read should carry. So relabel only
                # when it lands on annotation and the read's own form is not
                # annotated; otherwise keep the aligner's form. Both directions
                # occur on the hold-out, which is why this is a rule and not a
                # blanket skip:
                #   05e2f8d8  annotated 111N -> unannotated 114N   (must NOT move)
                #   3178286c  unannotated 109N -> annotated 114N   (SHOULD move)
                # Never decide it on score: the score always favours the merged
                # form, because the abutting deletion stops costing once it is
                # relabelled as intron. That is not read evidence — 05e2f8d8's
                # 1.128-unit "improvement" cleared even the annotated-canonical
                # evidence gate on exactly that artifact.
                if not ((chrom, js, je) in annotated_set
                        and (chrom, ns, ne) not in annotated_set):
                    if profile is not None:
                        profile.inc('candidates_dn_merge_twin')
                    continue

            _t_score = time.perf_counter() if profile is not None else 0.0
            score, delta = _score_junction(
                q, q_split, js, je, genome_seq,
                hp_pen=hp_pen, W=W, max_slide=max_slide,
                current_ns=ns,   # anchor: current N-op boundaries
                profile=profile,
                penalty_table=penalty_table,
            )
            _profile_time(profile, 'score_junction_call_wall', _t_score)

            # Tie-breakers (only matter when score is identical or within noise floor):
            is_alt   = 0 if (js == ns and je == ne) else 1  # current junction preferred
            # L1 distance from the aligner's own placement. Zero for the
            # incumbent, so it is consistent with is_alt by construction.
            move_dist = abs(js - ns) + abs(je - ne)
            _t_tiebreak = time.perf_counter() if profile is not None else 0.0
            tier     = _canonical_tier(js, je, genome_seq, strand)
            is_novel = 0 if (chrom, js, je) in annotated_set else 1
            _profile_time(profile, 'candidate_tiebreak_metadata', _t_tiebreak)

            # When the current junction is non-canonical, apply _CANONICAL_HP_PRIOR
            # (0.5 edit-distance units) as a discount to canonical-tier junctions so
            # that canonical alternatives win within the HP noise floor regardless of
            # which penalty table is in use.  Non-canonical candidates get no
            # discount.  When the current junction is canonical, compare raw scores.
            # The SAME line defines canonical here as above: a candidate whose own
            # acceptor is not AG must not collect the canonical prior — which is how
            # a GT-AT incumbent used to out-discount the real GT-AG alternative.
            if tier_beats_alt:
                canonical_discount = (
                    _CANONICAL_HP_PRIOR if tier <= _CANONICAL_TIER_MAX else 0.0
                )
                score_cmp = score - canonical_discount
            else:
                score_cmp = score
            if is_alt == 0:              # this candidate IS the read's current placement
                incumbent_score = score_cmp

            # Scoring priority (lower = better):
            #   1. score_cmp — binned when tier_beats_alt, raw otherwise
            #   2. tier / is_alt (order depends on current_tier — see above)
            #   3. is_alt / tier (the other one)
            #   4. is_novel  — annotated preferred over novel
            #   5. move_dist — at a genuine tie, take the SMALLER move
            #      (ISSUE-005(b)). This slot used to hold `abs(delta)` from the
            #      scorer, which is the applied SLIDE and is structurally 0 for
            #      every candidate (`max_slide` is API-compatibility only —
            #      `tests/test_junction_refiner.py` pins that contract). The slot
            #      was therefore a constant, and equal-scoring candidates were
            #      separated by nothing but (js, je) — the LOWER GENOMIC
            #      COORDINATE, an arbitrary leftward bias that has nothing to do
            #      with the read. The distance is now derived from coordinates
            #      instead: among candidates the read cannot distinguish, the one
            #      closest to where the aligner put it is the smaller claim.
            #      It is the FIFTH key and can never override score, tier, is_alt
            #      or annotation — all four still decide first.
            # Motif-blind drops the canonical-tier and annotation priors from the
            # tie-break (they collapse to constants), leaving score → is_alt → shift.
            tier_key = 0 if motif_blind else tier
            novel_key = 0 if motif_blind else is_novel
            if tier_beats_alt:
                # Current junction is non-canonical: prefer canonical alternatives
                candidate_tuple = (score_cmp, tier_key, is_alt, novel_key, move_dist, js, je, delta)
            else:
                # Current junction is acceptably canonical: prefer it at equal score
                candidate_tuple = (score_cmp, is_alt, tier_key, novel_key, move_dist, js, je, delta)
            ranked.append(candidate_tuple)
            if is_alt == 0:
                incumbent_tuple = candidate_tuple

        if not ranked:
            continue

        # --- Realizability: the ranking is over candidates the surgery can WRITE ---
        # The winner used to be the best-scoring candidate, full stop; if the
        # surgery then refused it (boundary-shift guard, span mismatch, the
        # both-boundary indel invariant) the read silently kept its stock
        # placement and the runner-up was never tried.  T0 read a138b2da
        # (SMA_7.12): the corrected rescue window (ISSUE-021) let an annotated
        # acceptor 19 nt DOWNSTREAM score 0.0 — the scorer's free-k prefix
        # matched the read's own exon-2 bases as "intron tail", i.e. the
        # incumbent alignment relabeled, not read evidence — the surgery refused
        # the 18-nt relabel as an indel-burden rise, and the annotated 3-nt donor
        # fix ranked second was discarded with it.  So: walk the ranking, dry-run
        # the surgery on the head, and drop a candidate that cannot be written.
        # The incumbent needs no surgery and always stops the walk.
        ranked.sort()
        best_tuple = None
        for _tup in ranked:
            _cjs, _cje = _tup[5], _tup[6]
            if (_cjs, _cje) == (ns, ne):
                best_tuple = _tup
                break
            if _realizable(read, cigar_idx, ns, ne, _cjs, _cje, genome_seq, strand, hp_pen, W):
                best_tuple = _tup
                break
            _bump('unrealizable_winner_skipped')
        if best_tuple is None:
            continue    # nothing writable and the incumbent is not a candidate: stay

        # best_tuple = (score, pri2, pri3, is_novel, move_dist, js, je, delta)
        # (the trailing `delta` is the scorer's applied slide, structurally 0;
        #  kept so the tuple shape still mirrors _score_junction's contract.)
        best_score_cmp = best_tuple[0]
        _, _, _, _, _, new_js, new_je, _ = best_tuple

        moves = (new_js != ns or new_je != ne)

        # --- Annotated-alternative rule (T0 4f9102d, RULING 3 (b) applied as a
        # decision instead of a freeze) -----------------------------------------
        # A non-canonical-class, unannotated destination may not win over an
        # annotated canonical-class candidate that shares one boundary with it
        # and lies within _ANNOT_ALT_DELTA on the other: within that distance the
        # read cannot tell them apart (an HP undercall or a 2-3 nt deletion at the
        # exon start prices the two placements differently by a fraction of a
        # unit), and the annotation is the evidence that decides.  Cohort reads:
        # 527c329f (canonical incumbent; GT-GA +1 beat the annotated GT-AG by
        # 0.125, the preponderance gate refused it and the read FROZE 12 nt off)
        # and 7628e0dd (GT-AC incumbent; GT-CA 3D beat the annotated GT-AG 5D).
        # The alternative REPLACES the winner, so the R1 hold and the gate below
        # judge an annotated canonical destination.  When the read CANNOT be
        # redirected — the surgery cannot write the alternative, or a scored
        # incumbent outranks it — the non-canonical winner is REFUSED, not let
        # through: RULING 3 (b) is that such a destination needs no annotated /
        # canonical alternative within delta, and the alternative's existence is
        # what the read has just shown.  (T0 4413bbd: 16 GSB/WT reads at the
        # chr1- CT..AT stock 183633152-183635514, tier 4, unannotated.  F1 skipped
        # the annotated AT-AC 154-516 as unwritable and took the CT..AT 152-516
        # two bases off it; this rule found 154-516, could not write it, fell
        # through, and the R1 hold and the gate below were out of scope for a
        # non-canonical incumbent — so a 0.185 score edge inside the noise floor
        # moved 16 reads onto a non-canonical site.  Baseline behavior was to
        # stay, because the unwritable annotated head was the winner.)  The one
        # exemption stays: when the alternative is the incumbent itself the rule
        # is silent and the preponderance gate decides, so its refusal accounting
        # (noncanon_destination_refused, the A/B off-switch) keeps its meaning.
        # Off under motif_blind, like every other annotation prior here.
        if (
            moves
            and not motif_blind
            and (chrom, new_js, new_je) not in annotated_set
            and _canonical_tier(new_js, new_je, genome_seq, strand) > _CANONICAL_TIER_MAX
        ):
            _alt = _annotated_alternative(
                ranked, chrom, new_js, new_je, genome_seq, strand, annotated_set,
            )
            if _alt is not None and (_alt[5], _alt[6]) != (ns, ne):
                _alt_js, _alt_je = _alt[5], _alt[6]
                _alt_refusal = ''
                if incumbent_tuple is not None and not (_alt < incumbent_tuple):
                    _alt_refusal = 'outranked'
                elif not _realizable(read, cigar_idx, ns, ne, _alt_js, _alt_je,
                                     genome_seq, strand, hp_pen, W):
                    _alt_refusal = 'unrealizable'
                if _alt_refusal:
                    moves = False
                    _bump('noncanon_dest_refused_annotated_alt')
                    _bump(f'noncanon_dest_refused_annotated_alt_{_alt_refusal}')
                else:
                    _bump('noncanon_dest_lost_to_annotated_alt')
                    best_tuple = _alt
                    best_score_cmp = _alt[0]
                    new_js, new_je = _alt_js, _alt_je
        # Move gate.  Two priors against a marginally-better-scoring displacement:
        #   * hold_margin      — a BLUNT prior: any move must beat the incumbent by it.
        #   * hp_drift_margin   — a TARGETED prior: only a move that slides a boundary
        #                         INTO a homopolymer run (the ubiquitous-undercall
        #                         drift that fabricates false non-canonical junctions)
        #                         must clear the extra margin; a move to a genuine
        #                         sequence transition (a real non-canonical acceptor)
        #                         is untouched, preserving motif-blind discovery.
        # Both default to 0.0 → byte-identical incumbent behaviour.
        eff_margin = hold_margin
        if moves and hp_drift_margin > 0.0:
            into_hp = (_hp_run_across(genome_seq, new_js, hp_drift_min_run) > 0 or
                       _hp_run_across(genome_seq, new_je, hp_drift_min_run) > 0)
            if into_hp:
                eff_margin += hp_drift_margin
                if profile is not None:
                    profile.inc('hp_drift_flagged')
        #   * microhom_drift_margin — the GENERAL analog of hp_drift_margin: a move
        #     whose boundary shift sits in a local MICROHOMOLOGY context (a near-tandem
        #     repeat at the drift distance, microhomology fraction >= microhom_threshold)
        #     is the non-homopolymer drift that fabricates false non-canonical junctions
        #     (spike-in-confirmed, HP-guard-blind). A move to a genuine transition (low
        #     microhomology, a real non-canonical site) is untouched. Default 0.0 → off.
        if moves and microhom_drift_margin > 0.0:
            if _move_microhomology(genome_seq, ns, ne, new_js, new_je) >= microhom_threshold:
                eff_margin += microhom_drift_margin
                if profile is not None:
                    profile.inc('microhom_drift_flagged')
        #   * drift_near_tie_cap — a READ-EVIDENCE ceiling on the read-BLIND drift
        #     margins (hp_drift + microhom_drift are decided from GENOMIC context only,
        #     so on their own they can veto a move the READ strongly supports). When
        #     > 0.0, cap the drift-added portion of eff_margin so the drift veto fires
        #     only within a near-tie band: veto_margin = max(hold_margin,
        #     min(eff_margin, drift_near_tie_cap)). hold_margin (read-agnostic blunt
        #     prior) is NEVER capped. NOTE (honest framing — see MICROHOM_AUDIT_SYNTHESIS):
        #     delta_improve, eff_margin and the cap all live on the SAME scalar (score)
        #     axis, so the cap BOUNDS the read-blind discovery-loss (a move with
        #     delta_improve >= cap is never drift-vetoed) but does NOT add a new
        #     discriminating signal inside the (0, cap) band. Its value is STRUCTURAL:
        #     it decouples hold_margin from the drift margins and makes the discovery-loss
        #     ceiling explicit + tunable. Default 0.0 → cap disabled → byte-identical.
        #   * drift_positional_gate — the read-evidence signal that CLOSES the read-blind
        #     fault (the cap only BOUNDS it — same score axis).  When a drift-context move
        #     would be vetoed, SPARE it if the read carries indel-robust POSITIONAL evidence
        #     for the moved acceptor: `_positional_signal` (hard-anchored edit distance,
        #     removing the scorer's free-k soft-clip escape) >= the gate.  This separates a
        #     real cryptic (read matches the moved exon2) from an error-driven drift (read
        #     matches the incumbent) INSIDE the delta near-tie band the cap cannot.  Default
        #     0.0 → gate off → byte-identical.  (Acceptor moves only; donor/both-boundary
        #     moves fall through to the margin/cap decision — conservative.)
        if moves and eff_margin > 0.0 and incumbent_score is not None:
            veto_margin = _effective_veto_margin(hold_margin, eff_margin, drift_near_tie_cap)
            if profile is not None and veto_margin < eff_margin:
                profile.inc('near_tie_cap_applied')
            if best_score_cmp > incumbent_score - veto_margin:
                spared = False
                if drift_positional_gate > 0.0:
                    psig = _positional_signal(genome_seq, q, q_split, ne, new_je)
                    if psig is not None and psig >= drift_positional_gate:
                        spared = True
                        if profile is not None:
                            profile.inc('positional_gate_spared')
                if not spared:
                    moves = False
                    if profile is not None:
                        profile.inc('move_margin_vetoes')

        # --- Annotated-canonical evidence gate (the R1 class) -----------------
        # The policy stated at the top of this loop — "within the sub-integer HP
        # noise floor (|ed_A - ed_B| < 1.0) canonical annotated junctions are
        # preferred" — was only ever implemented for the tier_beats_alt branch
        # (where _CANONICAL_HP_PRIOR discounts canonical candidates).  In the
        # other branch, where the incumbent IS canonical, candidates are ranked
        # on the RAW score, so a 0.03 edit-distance win could take an annotated
        # GT-AG junction onto a novel non-canonical one.  Measured on the Sumner
        # human panel: three such moves at margins 0.031 / 0.434 / 0.463, all far
        # inside the noise floor, each turning an annotated GT-AG into GT-GT /
        # GT-GA / CT-TC.
        #
        # So: when the incumbent is BOTH annotated and canonical, a candidate
        # that is not both must beat it by a full edit-distance unit.  Moves to
        # another annotated canonical junction (isoform swaps) and moves whose
        # incumbent is novel or non-canonical (the corrections 2H exists for) are
        # untouched.  Disabled under motif_blind, which decides on read evidence
        # alone by construction.
        if (
            moves
            and _ANNOTATED_CANONICAL_HOLD > 0.0
            and not motif_blind
            and incumbent_score is not None
            and current_tier < 4
            and (chrom, ns, ne) in annotated_set
        ):
            _win_tier = _canonical_tier(new_js, new_je, genome_seq, strand)
            _win_annot = (chrom, new_js, new_je) in annotated_set
            if not (_win_annot and _win_tier < 4):
                if best_score_cmp > incumbent_score - _ANNOTATED_CANONICAL_HOLD:
                    moves = False
                    _bump('annotated_canonical_holds')

        # --- Non-canonical-destination preponderance gate (ISSUE-018) ---------
        # The R1 hold above is a SCORE margin, and a stock D folded into the N
        # hands the candidate exactly that margin for free.  This gate asks the
        # structural question instead: does the read anchor the new site cleanly
        # on both sides?  Scope is deliberately the one class the cohort showed —
        # canonical-class incumbent, unannotated non-canonical-class winner; a
        # move whose destination is annotated (the 27 "onto a GENCODE intron whose
        # own motif is non-canonical") or canonical-class (every drift fix) is not
        # touched.  Disabled under motif_blind, like the hold.
        if (
            moves
            and _NONCANON_PREPONDERANCE
            and not motif_blind
            and current_tier <= _CANONICAL_TIER_MAX
            and (chrom, new_js, new_je) not in annotated_set
            and _canonical_tier(new_js, new_je, genome_seq, strand) > _CANONICAL_TIER_MAX
        ):
            _reason = _noncanon_destination_refusal(
                read, cigar_idx, ns, ne, new_js, new_je, genome_seq, strand,
                chrom, annotated_set, hp_pen, W,
            )
            if _reason:
                moves = False
                if profile is not None:
                    profile.inc('noncanon_destination_refused')
                    profile.inc(f'noncanon_destination_refused_{_reason}')
                if counters is not None:
                    counters['noncanon_destination_refused'] += 1
                    counters[f'noncanon_destination_refused_{_reason}'] += 1

        # Only emit a replacement if the junction actually changes.
        if moves:
            replacements.append((cigar_idx, ns, ne, new_js, new_je))
            if profile is not None:
                profile.inc('replacements_emitted')

    return replacements


# ---------------------------------------------------------------------------
# CIGAR surgery: apply junction replacement
# ---------------------------------------------------------------------------

def _apply_junction_replacement(
    read: pysam.AlignedSegment,
    cigar_idx: int,
    old_ns: int,
    old_ne: int,
    new_ns: int,
    new_ne: int,
    genome_seq: str,
    strand: str,
    hp_pen: float,
    W: int,
) -> bool:
    """Replace one N-op in-place and re-align flanking exon CIGAR ops.

    The flanking exon ops (query bases that overlap the boundary difference)
    are trimmed and re-emitted as M ops against the new junction.  The
    reference_start is updated if the leftmost exon changes.

    Args:
        read:       Modified in-place.
        cigar_idx:  Index of the N-op in read.cigartuples.
        old_ns/ne:  Current intron coordinates.
        new_ns/ne:  Replacement intron coordinates.
        genome_seq: Full chromosome sequence.
        strand:     '+' or '-'.
        hp_pen:     For local realignment (not used directly here).
        W:          Window for CIGAR reconstruction.

    Returns:
        True if CIGAR was modified.
    """
    from ..align.local_aligner import align_clip_to_exon, cigar_ops_to_str, cigar_str_to_ops

    cigar = list(read.cigartuples)
    q = read.query_sequence
    if not cigar or not q:
        return False

    # Delta in intron boundaries
    delta_start = new_ns - old_ns   # positive = intron grew on left (ate exon2 bases)
    delta_end   = new_ne - old_ne   # positive = intron shrunk on right (exon1 got more)

    new_cigar = list(cigar)
    new_ref_start = read.reference_start

    # --- Fast path: pure k-bp slide on splice-ambiguous bases ---
    #
    # When delta_start == delta_end == k (pure slide, no length change to the
    # intron) AND the k genome bases that flip role between intron-edge and
    # exon-edge are identical at both placements, the slide is a trivial CIGAR
    # transformation: extend the boundary =/M op on one side of N by k and
    # shrink the boundary =/M op on the other side by k.  The read base whose
    # role flips has the same identity at both genomic positions, so an =-op
    # at the old placement remains an =-op at the new placement.
    #
    # This avoids the boundary D/I insertions that the general path emits, which
    # are then mangled by the downstream indel corrector into degenerate
    # local-realignment CIGARs (e.g. 14=1D8=1D366N1I50= → 22D1M20I1M366N1I50=).
    #
    # The transformation is strand-agnostic: CIGAR ops are always in genomic
    # order, so we only care about which adjacent op is upstream (lower genomic
    # coord) and which is downstream (higher).  Strand only affects which end
    # is the donor vs acceptor, which the fast path doesn't need to know.
    if (
        delta_start == delta_end
        and delta_start != 0
        and abs(delta_start) <= 50  # same _MAX_BOUNDARY_SHIFT guard as below
        and 0 < cigar_idx < len(new_cigar) - 1
    ):
        k = delta_start  # signed slide magnitude (positive = N slid right)
        absk = abs(k)

        # Adjacent ops: must be =/M on both sides for the slide to remain valid
        # as a pure match-extension transformation.
        up_op, up_len = new_cigar[cigar_idx - 1]
        dn_op, dn_len = new_cigar[cigar_idx + 1]

        if up_op in (_EQ, _M) and dn_op in (_EQ, _M):
            # Identify the read base(s) whose role flips and the two genomic
            # positions they would align to.
            #
            # k > 0 (intron slides right by k): genome positions [old_ns,
            #   old_ns + k) flip from intron to upstream-exon; positions
            #   [old_ne, old_ne + k) flip from downstream-exon to intron.
            #   The read base previously aligned to genome[old_ne + i] is now
            #   aligned to genome[old_ns + i].  For an =-op to remain valid,
            #   genome[old_ns + i] == genome[old_ne + i] for i in [0, k).
            #
            # k < 0 (intron slides left by |k|): genome positions [old_ns - |k|,
            #   old_ns) flip from upstream-exon to intron; positions
            #   [old_ne - |k|, old_ne) flip from intron to downstream-exon.
            #   The read base previously aligned to genome[old_ns - 1 - i] is
            #   now aligned to genome[old_ne - 1 - i].  Need genome[old_ns - 1
            #   - i] == genome[old_ne - 1 - i] for i in [0, |k|).
            gs = len(genome_seq)
            ok = True
            if k > 0:
                if old_ne + k > gs or old_ns < 0:
                    ok = False
                else:
                    for i in range(k):
                        if genome_seq[old_ns + i].upper() != genome_seq[old_ne + i].upper():
                            ok = False
                            break
                # Shrinking side: downstream op must have length >= k
                if ok and dn_len < k:
                    ok = False
            else:  # k < 0
                if old_ne + k < 0 or old_ns > gs:
                    ok = False
                else:
                    for i in range(absk):
                        if genome_seq[old_ns - 1 - i].upper() != genome_seq[old_ne - 1 - i].upper():
                            ok = False
                            break
                # Shrinking side: upstream op must have length >= |k|
                if ok and up_len < absk:
                    ok = False

            if ok:
                # k > 0: upstream =/M gains k; downstream =/M loses k.
                # k < 0: upstream =/M loses |k|; downstream =/M gains |k|.
                if k > 0:
                    new_up_len = up_len + k
                    new_dn_len = dn_len - k
                else:
                    new_up_len = up_len + k  # k is negative → subtracts
                    new_dn_len = dn_len - k  # k is negative → adds

                # N length is unchanged (pure slide preserves intron length).
                n_len = old_ne - old_ns
                new_cigar[cigar_idx - 1] = (up_op, new_up_len)
                new_cigar[cigar_idx]     = (_N, n_len)
                new_cigar[cigar_idx + 1] = (dn_op, new_dn_len)

                # Span checks: ref span gains k from upstream and loses k from
                # downstream (or vice versa) — net zero.  Same for query span.
                read.cigartuples = new_cigar
                # reference_start unchanged (we never touched leading ops)
                return True
        # Fall through to general path if fast-path preconditions not met

    # --- Fix intron start boundary ---
    # If delta_start > 0: intron_start moved right → exon2 gained |delta_start| ref bases
    #                      (need to add M ops before N from exon2 query bases absorbed in old N)
    # If delta_start < 0: intron_start moved left → exon2 lost |delta_start| ref bases
    #                      (trim those bases from the last exon2 op before N)
    #
    # --- Fix intron end boundary ---
    # If delta_end > 0: intron_end moved right → exon1 lost |delta_end| ref bases
    # If delta_end < 0: intron_end moved left → exon1 gained |delta_end| ref bases

    # Replace just the N length; flanking ops are handled via re-query alignment.
    # Simple approach: update N length and adjust adjacent M/D/X ops by the deltas.
    # For the exon2 side (left of N, index cigar_idx-1):
    #   shrink/grow the last M-consuming op
    # For the exon1 side (right of N, index cigar_idx+1):
    #   shrink/grow the first M-consuming op

    new_n_len = new_ne - new_ns
    if new_n_len <= 0:
        return False

    # Guard: refuse replacements with unreasonably large boundary shifts.
    # Legitimate junction corrections are at most a few bp off; large deltas
    # indicate a mis-matched junction pair (e.g., an annotated junction from a
    # completely different gene that happens to be within search_radius).
    _MAX_BOUNDARY_SHIFT = 50  # bp
    if abs(delta_start) > _MAX_BOUNDARY_SHIFT or abs(delta_end) > _MAX_BOUNDARY_SHIFT:
        logger.debug(
            "_apply_junction_replacement: boundary shift too large "
            "(delta_start=%d, delta_end=%d) for read %s — skipping",
            delta_start, delta_end, read.query_name,
        )
        return False

    new_cigar[cigar_idx] = (_N, new_n_len)

    # --- Adjust exon2 flank ---
    # The challenge: M ops consume both ref AND query, so we can't simply shrink/grow
    # an M without disturbing the query span.  Instead we insert boundary ops:
    #
    #   delta_start > 0  (N start moved right; intron gave d ref bases to exon2)
    #     → those d ref positions had NO query bases (they were in the N)
    #     → encode as D(d) at the right edge of exon2: M(m)D(d)N(L')
    #     → ref: +d from D ✓;  query: unchanged ✓
    #
    #   delta_start < 0  (N start moved left; exon2 lost d ref bases into intron)
    #     → those d query bases that were in exon2 M are now "inside" the intron
    #     → encode as I(d) at the right edge of exon2 (before N): M(m-d)I(d)N(L')
    #     → ref: -d from shrunk M ✓;  query: unchanged (M loses d, I gains d) ✓
    # Track N-op index explicitly through inserts (do NOT search — reads may have
    # multiple N-ops, and a search could match the wrong one).
    n_idx = cigar_idx  # starts at original position; updated as inserts shift it

    if delta_start != 0:
        d = abs(delta_start)
        # Find the last ref-consuming op before n_idx
        ins_k = -1
        for k in range(n_idx - 1, -1, -1):
            if new_cigar[k][0] in _REF_CONSUMING:
                ins_k = k
                break
        if ins_k < 0:
            return False  # no ref-consuming op found before N

        op_k, len_k = new_cigar[ins_k]

        if delta_start > 0:
            # Exon2 gained d ref bases from the intron.  Encode as D(d) before N.
            new_cigar.insert(n_idx, (_D, d))
            n_idx += 1  # N shifted right by 1 due to insert
        else:
            # delta_start < 0: exon2 lost d ref bases into intron.
            # Walk backward from n_idx-1, consuming d ref bases (may span multiple ops).
            remaining_ref = d
            absorbed_q = 0
            ops_start = n_idx  # exclusive start: we remove ops in [ops_start, n_idx)
            leftover_op2: Optional[Tuple[int, int]] = None

            for k in range(n_idx - 1, -1, -1):
                op_k2, len_k2 = new_cigar[k]
                if op_k2 in _REF_CONSUMING:
                    if remaining_ref <= 0:
                        break
                    take_ref = min(len_k2, remaining_ref)
                    take_q   = take_ref if op_k2 in _QUERY_CONSUMING else 0
                    absorbed_q += take_q
                    remaining_ref -= take_ref
                    if take_ref < len_k2:
                        leftover_op2 = (op_k2, len_k2 - take_ref)
                        ops_start = k
                        break
                    else:
                        ops_start = k
                elif op_k2 in _QUERY_CONSUMING:
                    absorbed_q += len_k2
                    ops_start = k

            if remaining_ref > 0:
                return False

            # Remove consumed ops
            del new_cigar[ops_start: n_idx]
            n_idx = ops_start  # N shifted left
            if leftover_op2 is not None:
                new_cigar.insert(n_idx, leftover_op2)
                n_idx += 1
            # Append I(absorbed_q) right before N
            if absorbed_q > 0:
                new_cigar.insert(n_idx, (_I, absorbed_q))
                n_idx += 1

    # --- Adjust exon1 flank ---
    #   delta_end > 0  (N end moved right; exon1 lost d ref bases into intron)
    #     → those d query bases from exon1 M can't just vanish
    #     → encode as I(d) at the left edge of exon1: N(L')I(d)M(m-d)
    #     → ref: M loses d ✓;  query: unchanged (M loses d, I gains d) ✓
    #
    #   delta_end < 0  (N end moved left; exon1 gained d ref bases from intron)
    #     → those d positions had NO query bases (they were in the N)
    #     → encode as D(d) at the left edge of exon1: N(L')D(d)M(m)
    #     → ref: +d from D ✓;  query: unchanged ✓
    if delta_end != 0:
        d = abs(delta_end)

        if delta_end > 0:
            # Exon1 lost d ref bases into the intron.  Those bases were previously
            # aligned (M/=/X ops) and carried query bases with them.  We need to:
            #   1. Remove d ref-consuming bases from the start of exon1 (may span
            #      multiple ops, along with any I ops interleaved between them).
            #   2. Prepend I(absorbed_query) to preserve the query span.
            # Walk forward from n_idx+1, consuming ops until d ref bases absorbed.
            remaining_ref = d
            absorbed_q = 0
            ops_to_remove_end = n_idx + 1  # exclusive end index of consumed ops
            leftover_op: Optional[Tuple[int, int]] = None  # partial op remainder

            for k in range(n_idx + 1, len(new_cigar)):
                op_k, len_k = new_cigar[k]
                if op_k in _REF_CONSUMING:
                    if remaining_ref <= 0:
                        break
                    take_ref = min(len_k, remaining_ref)
                    take_q   = take_ref if op_k in _QUERY_CONSUMING else 0
                    absorbed_q += take_q
                    remaining_ref -= take_ref
                    if take_ref < len_k:
                        # Partial consumption — save the remainder
                        leftover_op = (op_k, len_k - take_ref)
                        ops_to_remove_end = k + 1
                        break
                    else:
                        ops_to_remove_end = k + 1
                elif op_k in _QUERY_CONSUMING:
                    # I/S op interleaved with ref ops: absorb its query bases too
                    absorbed_q += len_k
                    ops_to_remove_end = k + 1

            if remaining_ref > 0:
                # Could not absorb all d ref bases (exon1 too short)
                return False

            # Remove consumed ops, optionally re-insert leftover
            del new_cigar[n_idx + 1: ops_to_remove_end]
            if leftover_op is not None:
                new_cigar.insert(n_idx + 1, leftover_op)
            # Prepend I(absorbed_q) right after N to preserve query span
            if absorbed_q > 0:
                new_cigar.insert(n_idx + 1, (_I, absorbed_q))

        else:
            # Exon1 gained |d| ref bases from the intron.  Those bases had NO
            # query counterpart (they were in the N-op).  Encode as D(d).
            new_cigar.insert(n_idx + 1, (_D, d))

    # Validate: total ref span must be preserved (sum ref ops + N = constant)
    old_ref_span = sum(l for op, l in cigar     if op in _REF_CONSUMING_POS)
    new_ref_span = sum(l for op, l in new_cigar if op in _REF_CONSUMING_POS)
    if old_ref_span != new_ref_span:
        logger.debug(
            "refine_junction: ref span mismatch (%d → %d) for read %s; skipping",
            old_ref_span, new_ref_span, read.query_name,
        )
        return False

    # Validate: total query span unchanged
    old_q_span = sum(l for op, l in cigar     if op in _QUERY_CONSUMING)
    new_q_span = sum(l for op, l in new_cigar if op in _QUERY_CONSUMING)
    if old_q_span != new_q_span:
        logger.debug(
            "refine_junction: query span mismatch (%d → %d) for read %s; skipping",
            old_q_span, new_q_span, read.query_name,
        )
        return False

    # INVARIANT: refuse a BOTH-BOUNDARY move that increases the read's indel burden.
    #
    # The general path preserves the query span by re-labelling boundaries with
    # COMPENSATING I/D ops — it never re-aligns the flank.  When BOTH the donor and the
    # acceptor shift (delta_start != 0 AND delta_end != 0) and the move is not a clean
    # microhomology slide (those return early via the fast path), it can only realize
    # the move by adding compensating indel on BOTH flanks: a pure k-bp slide →
    # I(k) … N … D(k), an asymmetric both-shift → D(a) … N … D(b).  The exon SEQUENCE
    # stays where the aligner put it while only the N-op COORDINATE moves — fabricating
    # a false junction position (and the downstream indel corrector mangles it further,
    # not better — see the fast-path note above).  On real ONT DRS this was ~85–95% of
    # "moved" reads at the SMA leads (dev/REPLACER_COMPENSATING_INDEL_BUG.md), a phantom
    # 6–48 bp "drift".  Refinement corrects ONE splice site at a time; a simultaneous
    # donor+acceptor relocation via compensating indels is the fabrication signature.
    #
    # Single-boundary corrections (donor-only or acceptor-only) are NOT touched — they
    # move one splice site and the indel they add represents a real intron-length change
    # at that site (e.g. 10M100N10M → 10M3D97N10M).  A move that REDUCES indel burden
    # (cleaning a boundary error) is always applied.  Refused reads keep their incumbent
    # (raw) placement — the conservative, correct outcome.
    if delta_start != 0 and delta_end != 0:
        old_indel = sum(l for op, l in cigar     if op in (_I, _D))
        new_indel = sum(l for op, l in new_cigar if op in (_I, _D))
        if new_indel > old_indel:
            logger.debug(
                "refine_junction: both-boundary move adds compensating indel "
                "(%d → %d) for read %s — unsupported relocation, refusing",
                old_indel, new_indel, read.query_name,
            )
            return False

    read.cigartuples = new_cigar
    if new_ref_start != read.reference_start:
        read.reference_start = new_ref_start

    return True


