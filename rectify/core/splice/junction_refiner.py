def _apply_replacements_to_read(
    read: pysam.AlignedSegment,
    replacements: list,
    genome_seq: str,
    strand: str,
    hp_pen: float,
    W: int,
) -> Tuple[pysam.AlignedSegment, bool]:
    """Apply junction replacements to *read* and return (modified_read, any_applied).

    Returns the original *read* unchanged if no replacements apply or if the
    copy fails.
    """
    try:
        modified_read = read.__copy__()
    except Exception:
        return read, False

    any_applied = False
    for cigar_idx, old_ns, old_ne, new_ns, new_ne in sorted(
        replacements, key=lambda r: -r[0]
    ):
        try:
            applied = _apply_junction_replacement(
                modified_read, cigar_idx, old_ns, old_ne, new_ns, new_ne,
                genome_seq, strand, hp_pen, W,
            )
            any_applied = any_applied or applied
        except Exception as exc:
            logger.debug(
                "_apply_junction_replacement failed for %s: %s",
                read.query_name, exc,
            )

    if any_applied:
        # Strip MD and cs tags from modified reads: the CIGAR has been
        # changed (boundary D/I ops inserted) so the MD string is now
        # invalid.  Without MD, downstream tools (pysam indel corrector)
        # skip MD-based processing, which is correct.  Also strip cs
        # (cigar string in cs notation) for the same reason.
        try:
            modified_read.set_tags([
                t for t in modified_read.tags if t[0] not in ('MD', 'cs')
            ])
        except Exception:
            pass

    return modified_read, any_applied


def _run_sequential(
    input_bam: str,
    output_bam: str,
    genome: Dict[str, str],
    junctions_idx: Dict,
    annotated_set: Set,
    stats: Dict[str, int],
    hp_pen: float,
    W: int,
    max_slide: int,
    search_radius: int,
    max_boundary_shift: int,
    boundary_error_window: int,
    max_junction_size: Optional[int],
    max_candidates_per_nop: Optional[int],
    penalty_table: Optional[HpPenaltyTable],
    penalty_table_set: Optional[PenaltyTableSet] = None,
    motif_blind: bool = False,
    hold_margin: float = 0.0,
    hp_drift_margin: float = 0.0,
    hp_drift_min_run: int = 4,
    microhom_drift_margin: float = 0.0,
    microhom_threshold: float = 0.5,
    drift_near_tie_cap: float = 0.0,
    drift_positional_gate: float = 0.0,
    profile: Optional[JunctionRefineProfile] = None,
) -> None:
    """Single-threaded sequential junction refinement (original code path)."""
    sample_rate = profile.sample_rate if profile is not None else 1
    counters: Counter = Counter()
    with pysam.AlignmentFile(input_bam, 'rb') as bam_in, \
         pysam.AlignmentFile(output_bam, 'wb', header=bam_in.header) as bam_out:

        for read in bam_in:
            stats['total'] += 1
            if read.is_unmapped or not read.cigartuples:
                bam_out.write(read)
                stats['unchanged'] += 1
                continue

            if not any(op == _N for op, _ in read.cigartuples):
                bam_out.write(read)
                stats['unchanged'] += 1
                continue

            stats['n_op_reads'] += 1
            strand = '-' if read.is_reverse else '+'
            chrom = standardize_chrom_name(read.reference_name)
            genome_seq = genome.get(chrom, '')
            if not genome_seq:
                bam_out.write(read)
                stats['unchanged'] += 1
                continue

            eff_table = (penalty_table_set.for_read(read)
                         if penalty_table_set is not None else penalty_table)
            try:
                read_profile = (
                    profile
                    if profile is not None and (stats['n_op_reads'] % sample_rate == 0)
                    else None
                )
                replacements = refine_read_junctions(
                    read, junctions_idx, annotated_set, genome_seq, strand,
                    hp_pen=hp_pen, W=W, max_slide=max_slide,
                    search_radius=search_radius,
                    max_boundary_shift=max_boundary_shift,
                    boundary_error_window=boundary_error_window,
                    max_junction_size=max_junction_size,
                    max_candidates_per_nop=max_candidates_per_nop,
                    profile=read_profile,
                    penalty_table=eff_table,
                    motif_blind=motif_blind,
                    hold_margin=hold_margin,
                    hp_drift_margin=hp_drift_margin,
                    hp_drift_min_run=hp_drift_min_run,
                    microhom_drift_margin=microhom_drift_margin,
                    microhom_threshold=microhom_threshold,
                    drift_near_tie_cap=drift_near_tie_cap,
                    drift_positional_gate=drift_positional_gate,
                    counters=counters,
                )
            except Exception as exc:
                logger.debug("refine_read_junctions failed for %s: %s", read.query_name, exc)
                bam_out.write(read)
                stats['errors'] += 1
                continue

            if not replacements:
                bam_out.write(read)
                stats['unchanged'] += 1
                continue

            modified_read, any_applied = _apply_replacements_to_read(
                read, replacements, genome_seq, strand, hp_pen, W,
            )
            bam_out.write(modified_read)
            if any_applied:
                stats['refined'] += 1
            else:
                stats['unchanged'] += 1
    for key, n in counters.items():
        stats[key] = stats.get(key, 0) + int(n)


def _run_parallel(
    input_bam: str,
    output_bam: str,
    genome: Dict[str, str],
    junctions_idx: Dict,
    annotated_set: Set,
    stats: Dict[str, int],
    hp_pen: float,
    W: int,
    max_slide: int,
    search_radius: int,
    max_boundary_shift: int,
    boundary_error_window: int,
    max_junction_size: Optional[int],
    max_candidates_per_nop: Optional[int],
    penalty_table: Optional[HpPenaltyTable],
    n_workers: int,
    batch_size: int,
    penalty_table_set: Optional[PenaltyTableSet] = None,
    motif_blind: bool = False,
    hold_margin: float = 0.0,
    hp_drift_margin: float = 0.0,
    hp_drift_min_run: int = 4,
    microhom_drift_margin: float = 0.0,
    microhom_threshold: float = 0.5,
    drift_near_tie_cap: float = 0.0,
    drift_positional_gate: float = 0.0,
    profile: Optional[JunctionRefineProfile] = None,
) -> None:
    """Parallel junction refinement using a multiprocessing Pool.

    Phase 1: Read all reads; write pass-throughs immediately; collect N-op
             reads as SAM strings.
    Phase 2: Process N-op batches in parallel workers.  The shared state
             (header, pool index, annotated set, genome, scoring kwargs) is
             installed in every worker by the pool INITIALIZER, so the driver
             is start-method independent (ISSUE-025): under ``fork`` the
             initargs are inherited zero-copy, under ``spawn`` they are
             pickled once per worker.
    Phase 3: Apply replacements in main process and write to output BAM.

    A worker or pool failure is re-raised as a RuntimeError naming the start
    method and worker count, so the caller cannot mistake "2H did nothing"
    for "2H had nothing to do".
    """
    # Phase 1: separate pass-through reads from N-op reads, write pass-throughs
    _t_scan = time.perf_counter() if profile is not None else 0.0
    n_op_sams: List[str] = []
    with pysam.AlignmentFile(input_bam, 'rb') as bam_in:
        header_dict = bam_in.header.to_dict()
        for read in bam_in:
            stats['total'] += 1
            if (read.is_unmapped or not read.cigartuples
                    or not any(op == _N for op, _ in read.cigartuples)):
                stats['unchanged'] += 1
                continue
            stats['n_op_reads'] += 1
            n_op_sams.append(read.to_string())
    _profile_time(profile, 'parallel_bam_scan_collect_nop_reads', _t_scan)

    if not n_op_sams:
        # No N-op reads: just copy the BAM
        with pysam.AlignmentFile(input_bam, 'rb') as bam_in, \
             pysam.AlignmentFile(output_bam, 'wb', header=bam_in.header) as bam_out:
            for read in bam_in:
                bam_out.write(read)
        return

    # Worker state travels through the pool initializer (ISSUE-025).  The
    # header goes as its dict (pysam.AlignmentHeader is rebuilt in the worker);
    # everything else is plain Python / picklable.  Under 'fork' none of this
    # is pickled — the initargs are inherited copy-on-write exactly as the old
    # module-global was — so Linux production keeps its zero-copy behavior.
    worker_state = {
        'header_dict': header_dict,
        'junctions_idx': junctions_idx,
        'annotated_set': annotated_set,
        'genome': genome,
        'kwargs': {
            'hp_pen': hp_pen, 'W': W, 'max_slide': max_slide,
            'search_radius': search_radius,
            'max_boundary_shift': max_boundary_shift,
            'boundary_error_window': boundary_error_window,
            'max_junction_size': max_junction_size,
            'max_candidates_per_nop': max_candidates_per_nop,
            'penalty_table': penalty_table,
            'motif_blind': motif_blind,
            'hold_margin': hold_margin,
            'hp_drift_margin': hp_drift_margin,
            'hp_drift_min_run': hp_drift_min_run,
            'microhom_drift_margin': microhom_drift_margin,
            'microhom_threshold': microhom_threshold,
            'drift_near_tie_cap': drift_near_tie_cap,
            'drift_positional_gate': drift_positional_gate,
        },
        'penalty_table_set': penalty_table_set,
        'profile_enabled': profile is not None,
        'profile_sample_rate': profile.sample_rate if profile is not None else 1,
    }

    # Trigger numba JIT compilation before the pool starts: forked workers
    # inherit the compiled code; spawned workers reload it from numba's
    # on-disk cache, and any JIT failure surfaces here, in the parent.
    if _NUMBA_AVAILABLE:
        _warmup_numba_dp()

    bam_hdr = pysam.AlignmentHeader.from_dict(header_dict)
    batches = [n_op_sams[i:i + batch_size] for i in range(0, len(n_op_sams), batch_size)]
    all_results: List[Tuple[str, List]] = []

    # Phase 2: parallel scoring
    ctx = _get_refiner_mp_context()
    _t_workers = time.perf_counter() if profile is not None else 0.0
    try:
        with ctx.Pool(n_workers, initializer=_init_worker_pool_state,
                      initargs=(worker_state,)) as pool:
            for batch_results in pool.imap_unordered(_refine_read_batch, batches):
                if isinstance(batch_results, dict):
                    all_results.extend(batch_results.get('results', []))
                    if profile is not None:
                        profile.merge(batch_results.get('profile'))
                    for key, n in (batch_results.get('counters') or {}).items():
                        stats[key] = stats.get(key, 0) + int(n)
                else:
                    all_results.extend(batch_results)
    except Exception as exc:
        logger.error(
            "refine_bam_junctions: parallel driver failed (start method %s, %d workers): %s",
            ctx.get_start_method(), n_workers, exc,
        )
        raise RuntimeError(
            f"Module 2H parallel driver failed (start method "
            f"{ctx.get_start_method()!r}, {n_workers} workers): {exc!r}"
        ) from exc
    _profile_time(profile, 'parallel_worker_scoring', _t_workers)
    if len(all_results) != len(n_op_sams):
        raise RuntimeError(
            f"Module 2H parallel driver returned {len(all_results)} results for "
            f"{len(n_op_sams)} N-op reads"
        )

    # Phase 3: write all output (pass-throughs first, then N-op results)
    _t_write = time.perf_counter() if profile is not None else 0.0
    with pysam.AlignmentFile(input_bam, 'rb') as bam_in, \
         pysam.AlignmentFile(output_bam, 'wb', header=bam_in.header) as bam_out:

        # Write pass-through reads from input
        for read in bam_in:
            if (read.is_unmapped or not read.cigartuples
                    or not any(op == _N for op, _ in read.cigartuples)):
                bam_out.write(read)

        # Write N-op reads with replacements applied
        for sam_str, replacements in all_results:
            read = pysam.AlignedSegment.fromstring(sam_str, bam_hdr)
            if not replacements:
                bam_out.write(read)
                stats['unchanged'] += 1
                continue
            chrom = standardize_chrom_name(read.reference_name)
            genome_seq = genome.get(chrom, '')
            strand = '-' if read.is_reverse else '+'
            modified_read, any_applied = _apply_replacements_to_read(
                read, replacements, genome_seq, strand, hp_pen, W,
            )
            bam_out.write(modified_read)
            if any_applied:
                stats['refined'] += 1
            else:
                stats['unchanged'] += 1
    _profile_time(profile, 'parallel_output_write_apply_replacements', _t_write)


def _warmup_numba_dp() -> None:
    """Trigger Numba JIT compilation with a tiny dummy call.

    Called before Pool() creation so forked workers inherit the compiled
    function from cache rather than recompiling independently.
    """
    if not _NUMBA_AVAILABLE:
        return
    import numpy as np
    from .hp_penalty import _score_hp_dp_numba
    q = np.array([65, 84], dtype=np.uint8)   # "AT"
    r = np.array([65, 84, 65], dtype=np.uint8)  # "ATA"
    dc = np.array([0.5, 1.0, 0.5], dtype=np.float64)
    ic = np.array([1.25, 1.25], dtype=np.float64)
    _score_hp_dp_numba(q, r, dc, ic)


