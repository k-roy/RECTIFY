def refine_bam_junctions(
    input_bam: str,
    output_bam: str,
    aligner_bams: List[str],
    annotated_junctions: Set[Tuple],
    genome: Dict[str, str],
    hp_pen: float = 0.25,
    W: int = 15,
    max_slide: int = 10,
    search_radius: int = 5000,
    max_boundary_shift: int = 50,
    boundary_error_window: int = 10,
    max_junction_size: Optional[int] = None,
    max_candidates_per_nop: Optional[int] = None,
    sort_and_index: bool = True,
    penalty_table_path: Optional[str] = None,
    str_penalty_table_path: Optional[str] = None,
    prebuilt_junction_pool: Optional[Set] = None,
    prebuilt_annotated_set: Optional[Set] = None,
    sort_threads: int = 1,
    n_workers: int = 1,
    batch_size: int = 200,
    penalty_table_set: Optional['PenaltyTableSet'] = None,
    profile_path: Optional[str] = None,
    profile_sample_rate: int = 1,
    motif_blind: bool = False,
    hold_margin: float = 0.0,
    hp_drift_margin: float = 0.0,
    hp_drift_min_run: int = 4,
    microhom_drift_margin: float = 0.0,
    microhom_threshold: float = 0.5,
    drift_near_tie_cap: float = 0.0,
    drift_positional_gate: float = 0.0,
) -> Dict[str, int]:
    """Refine all N-op junctions in a BAM file.

    Writes a new BAM with improved N-op boundaries.  Reads without N-ops,
    or where no better junction is found, are passed through unchanged.

    Args:
        input_bam:            Path to input consensus BAM.
        output_bam:           Path to write refined BAM.
        aligner_bams:         Per-aligner BAM paths for junction pool.
        annotated_junctions:  From ``load_annotated_junctions()``.
        genome:               Dict mapping chrom → sequence.
        hp_pen:               Homopolymer penalty (tunable).
        W:                    Retained for API compatibility; unused by the
                              current HP-anchored semi-global implementation.
        max_slide:            Retained for API compatibility; unused by the
                              current HP-anchored semi-global implementation.
        max_boundary_shift:   Max allowed shift of either intron boundary (bp).
                              Prevents false-positive matches from junctions
                              in adjacent genes within search_radius.
        search_radius:        Junction search radius (bp).
        max_junction_size:    Optional maximum observed/candidate junction
                              length.  Applied when building a pool from BAMs
                              and when querying a pre-built pool.
        max_candidates_per_nop:
                              Optional deterministic cap on candidates scored
                              per N-op after candidate ranking.
        sort_and_index:       Sort and index the output BAM when True.
        penalty_table_path:   Optional path to ``penalty_scores.tsv`` produced
                              by ``empirical_cigar_error_profiler.py``.  When
                              provided, overrides the heuristic del/ins cost
                              step-function with empirical per-HP-length values.
                              Ignored when *penalty_table_set* is provided.
        penalty_table_set:    Optional :class:`PenaltyTableSet` holding
                              per-UMI-bin tables.  When provided, each read's
                              UMI-count tag (default ``XC``) is read to select
                              the appropriate table.  Takes precedence over
                              *penalty_table_path*.

    Returns:
        Stats dict with keys: total, n_op_reads, refined, unchanged, errors.
    """
    profile = JunctionRefineProfile(profile_sample_rate) if profile_path else None
    penalty_table: Optional[HpPenaltyTable] = None
    if penalty_table_path:
        _t_penalty = time.perf_counter() if profile is not None else 0.0
        try:
            penalty_table = HpPenaltyTable.from_tsv(penalty_table_path, str_path=str_penalty_table_path)
            logger.info(
                "refine_bam_junctions: loaded empirical penalty table from %s",
                penalty_table_path,
            )
        except Exception as exc:
            logger.warning(
                "refine_bam_junctions: failed to load penalty table from %s: %s "
                "— falling back to heuristic scoring",
                penalty_table_path, exc,
            )
        _profile_time(profile, 'penalty_table_load', _t_penalty)
    stats = dict(total=0, n_op_reads=0, refined=0, unchanged=0, errors=0,
                 noncanon_destination_refused=0)

    # Build junction pool and index.
    # When prebuilt_junction_pool is provided (from `rectify prescan`), use it
    # directly and skip BAM collection — used for chunked correction pipelines.
    if prebuilt_junction_pool is not None:
        _t_pool = time.perf_counter() if profile is not None else 0.0
        all_junctions = prebuilt_junction_pool
        annotated_set = prebuilt_annotated_set if prebuilt_annotated_set is not None else set()
        logger.info(
            "refine_bam_junctions: using pre-built pool (%d junctions, %d annotated)",
            len(all_junctions), len(annotated_set),
        )
        _profile_time(profile, 'junction_pool_load_or_assign', _t_pool)
    else:
        _t_pool = time.perf_counter() if profile is not None else 0.0
        all_junctions, annotated_set = build_junction_pool(
            aligner_bams,
            annotated_junctions,
            max_junction_size=max_junction_size,
        )
        logger.info(
            "refine_bam_junctions: pool has %d junctions (%d annotated)",
            len(all_junctions), len(annotated_set),
        )
        _profile_time(profile, 'junction_pool_build', _t_pool)
    _t_index = time.perf_counter() if profile is not None else 0.0
    junctions_idx = _build_junction_index(all_junctions)
    _profile_time(profile, 'junction_index_build', _t_index)
    if profile is not None:
        profile.inc('pool_junctions', len(all_junctions))
        profile.inc('pool_annotated_junctions', len(annotated_set))

    if n_workers > 1:
        _run_parallel(
            input_bam, output_bam, genome, junctions_idx, annotated_set, stats,
            hp_pen, W, max_slide, search_radius, max_boundary_shift,
            boundary_error_window, max_junction_size, max_candidates_per_nop,
            penalty_table, n_workers, batch_size,
            penalty_table_set=penalty_table_set, motif_blind=motif_blind,
            hold_margin=hold_margin, hp_drift_margin=hp_drift_margin,
            hp_drift_min_run=hp_drift_min_run, profile=profile,
            microhom_drift_margin=microhom_drift_margin,
            microhom_threshold=microhom_threshold,
            drift_near_tie_cap=drift_near_tie_cap,
            drift_positional_gate=drift_positional_gate,
        )
    else:
        _run_sequential(
            input_bam, output_bam, genome, junctions_idx, annotated_set, stats,
            hp_pen, W, max_slide, search_radius, max_boundary_shift,
            boundary_error_window, max_junction_size, max_candidates_per_nop,
            penalty_table,
            penalty_table_set=penalty_table_set, motif_blind=motif_blind,
            hold_margin=hold_margin, hp_drift_margin=hp_drift_margin,
            hp_drift_min_run=hp_drift_min_run, profile=profile,
            microhom_drift_margin=microhom_drift_margin,
            microhom_threshold=microhom_threshold,
            drift_near_tie_cap=drift_near_tie_cap,
            drift_positional_gate=drift_positional_gate,
        )

    if sort_and_index:
        try:
            _t_sort = time.perf_counter() if profile is not None else 0.0
            _sort_and_index(output_bam, n_threads=sort_threads)
            _profile_time(profile, 'sort_and_index_output_bam', _t_sort)
        except Exception as exc:
            # Do NOT swallow this: an unsorted/unindexed output_bam is not a
            # usable refined BAM. A caller that promotes output_bam to its
            # "current" BAM on a normal return (e.g. correct_command.py's
            # Module 2H step) would silently carry that broken file forward,
            # surfacing as an unrelated-looking failure much later. Log at
            # ERROR (the debuggable moment) and re-raise so this failure is
            # attributed to its real cause, not lost.
            logger.error(
                "refine_bam_junctions: sort/index failed for %s: %s",
                output_bam, exc,
            )
            raise RuntimeError(
                f"refine_bam_junctions: sort/index failed for output BAM "
                f"{output_bam!r}"
            ) from exc

    logger.info(
        "refine_bam_junctions done: %d total, %d with N-ops, %d refined, %d unchanged, "
        "%d errors, %d noncanon_destination_refused",
        stats['total'], stats['n_op_reads'], stats['refined'],
        stats['unchanged'], stats['errors'], stats['noncanon_destination_refused'],
    )
    if profile is not None:
        profile.counts.update({f"final_stats_{k}": int(v) for k, v in stats.items()})
        summary = profile.to_summary()
        out_path = Path(profile_path)
        out_path.parent.mkdir(parents=True, exist_ok=True)
        with open(out_path, 'w') as fh:
            json.dump(summary, fh, indent=2, sort_keys=True)
        logger.info("refine_bam_junctions: wrote profile summary to %s", out_path)
    return stats


def _sort_and_index(bam_path: str, n_threads: int = 1) -> None:
    """Sort and index a BAM file using samtools via subprocess.

    Uses subprocess (not pysam.sort/pysam.index) to avoid heap corruption
    bugs in pysam's C-level sort on CentOS 7 / older glibc.

    Args:
        bam_path:  Path to the BAM file to sort and index in place.
        n_threads: Number of threads to pass to ``samtools sort`` and
                   ``samtools index`` via ``-@``.  Defaults to 1.

    Raises:
        FileNotFoundError: If samtools cannot be located on PATH or in the
            active conda/venv environment's bin directory.
    """
    import os
    import shutil
    import subprocess
    import sys

    # Resolve samtools: check PATH first, then the conda/venv env bin dir
    # that contains the current Python interpreter (robust across platforms
    # where correction job scripts may not export the full conda PATH).
    samtools = shutil.which('samtools')
    if samtools is None:
        candidate = os.path.join(os.path.dirname(sys.executable), 'samtools')
        if os.path.isfile(candidate) and os.access(candidate, os.X_OK):
            samtools = candidate
    if samtools is None:
        raise FileNotFoundError(
            "samtools not found on PATH or in the active environment "
            f"({os.path.dirname(sys.executable)}). "
            "Add samtools to PATH or install it into the rectify conda env."
        )

    tmp = bam_path + '.tmp.bam'
    subprocess.run(
        [samtools, 'sort', f'-@{n_threads}', '-o', tmp, bam_path],
        check=True, capture_output=True,
    )
    os.replace(tmp, bam_path)
    subprocess.run(
        [samtools, 'index', f'-@{n_threads}', bam_path],
        check=True, capture_output=True,
    )


